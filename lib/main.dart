import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';

import 'config/saved_world.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/home_screen.dart';
import 'services/server_clock.dart';
import 'state/app_settings.dart';
import 'widgets/light_screens_observer.dart';
import 'theme/conquera_theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Anonymous auth gives every player a stable uid (used as the
  // players/ doc id and provinces.ownerId). Firebase keeps it on the device,
  // so reopening the app signs in as the same player again.
  if (FirebaseAuth.instance.currentUser == null) {
    await FirebaseAuth.instance.signInAnonymously();
  }
  debugPrint('Signed in anonymously: ${FirebaseAuth.instance.currentUser!.uid}');

  await ServerClock.init();

  await AppSettings.load();
  final lastWorld = await SavedWorld.load();
  // Home is always light. (If a world opens straight away, the observer
  // switches back once the map is showing.)
  if (lastWorld == null) ConqueraColors.override = ConqueraMode.light;
  runApp(ConqueraApp(initialWorldId: lastWorld));
}

class ConqueraApp extends StatelessWidget {
  /// The world the player was in last time; opened automatically.
  final String? initialWorldId;

  const ConqueraApp({super.key, this.initialWorldId});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Conquera',
      debugShowCheckedModeBanner: false,
      theme: buildConqueraTheme(),
      navigatorObservers: [LightScreensObserver()],
      home: HomeScreen(autoEnterWorldId: initialWorldId),
    );
  }
}