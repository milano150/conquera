import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';

import 'config/saved_world.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/home_screen.dart';
import 'screens/loading_screen.dart';
import 'services/server_clock.dart';
import 'state/app_settings.dart';
import 'widgets/fade_route.dart';
import 'widgets/light_screens_observer.dart';
import 'theme/conquera_theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Anonymous auth gives every player a stable uid (used as the
  // players/ doc id and provinces.ownerId). Firebase keeps it on the device,
  // so reopening the app signs in as the same player again.
  if (FirebaseAuth.instance.currentUser == null) {
    await FirebaseAuth.instance.signInAnonymously();
  }
  debugPrint('Signed in anonymously: ${FirebaseAuth.instance.currentUser!.uid}');

  await ServerClock.init();

  await AppSettings.load();
  final lastWorld = await SavedWorld.load();
  // Home and the loading screen are always light. (The observer switches
  // back once the map is showing.)
  ConqueraColors.override = ConqueraMode.light;
  runApp(ConqueraApp(initialWorldId: lastWorld));
}

class ConqueraApp extends StatelessWidget {
  /// The world the player was in last time; opened automatically.
  final String? initialWorldId;

  const ConqueraApp({super.key, this.initialWorldId});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Conquera',
      debugShowCheckedModeBanner: false,
      theme: buildConqueraTheme(),
      navigatorObservers: [LightScreensObserver()],
      // With a saved world the loading screen sits on top of the home screen:
      // it plays first, then the world opens. Back to lobby (or a world that
      // is gone) reveals the home screen underneath.
      // Required alongside onGenerateInitialRoutes (which can't be combined
      // with `home`); any named route falls back to the home screen.
      onGenerateRoute: (settings) => MaterialPageRoute<void>(
        settings: settings,
        builder: (_) => const HomeScreen(),
      ),
      onGenerateInitialRoutes: (_) => [
        MaterialPageRoute<void>(
          settings: const RouteSettings(name: Navigator.defaultRouteName),
          builder: (_) => const HomeScreen(),
        ),
        if (initialWorldId != null)
          FadeRoute<void>(
            settings: const RouteSettings(name: kLightRouteName),
            builder: (_) =>
                LoadingScreen(gameId: initialWorldId!, validate: true),
          ),
      ],
    );
  }
}