  /// Area of one country in km². Unknown ids count as 0, so a map id
  /// missing from the table never breaks the leaderboard.
  static int areaOf(String provinceId) => areaKm2[provinceId] ?? 0;

  /// Combined area of an empire (a player's owned province ids).
  static int totalArea(Iterable<String> provinceIds) {
    var total = 0;
    for (final id in provinceIds) {
      total += areaOf(id);
    }
    return total;
  }
